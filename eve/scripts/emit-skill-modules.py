#!/usr/bin/env python3
"""emit-skill-modules.py: write Eve's view of the skills tree (KTD1 shape a, KTD9).

Every skills/<name>/SKILL.md gets one flat module, eve/agent/skills/<name>.ts, that carries
the package's data: the description, the SKILL.md body and every sibling file (text as a
string, a file that is not valid UTF-8 as base64 decoded at load). The built agent reads
nothing from skills/ at run time; the modules are generated copies held to skills/ by
--check. Each module exports the package as `skillPackage` beside its default defineSkill.
The manual-only skills (frontmatter `disable-model-invocation: true`) get no module of their
own: their packages go into agent/lib/manual-only-packages.ts (Eve takes every file in
agent/skills/ for a skill), which the hand-written resolver agent/skills/manual-only.ts
serves. The versions a run record carries go into
agent/lib/versions.ts: Eve's from the exact pin in eve/package.json, the product's from the
product's package.json.

Default mode writes missing or drifted files and removes generated modules whose folder is
gone; a second run changes nothing. --check changes nothing and exits 1 on a folder without
its module, a module without its folder, a module for a manual-only skill, a drifted file,
or a foreign file.

Usage: emit-skill-modules.py [--check]
Exit:  0 = in sync (or synced) · 1 = drift found in --check mode, or a foreign file
"""
import base64
import json
import re
import sys
from pathlib import Path

EVE = Path(__file__).resolve().parent.parent
SKILLS = EVE.parent / "skills"
MODULES = EVE / "agent" / "skills"
RESOLVER = "manual-only.ts"
MANUAL_PACKAGES = EVE / "agent" / "lib" / "manual-only-packages.ts"
VERSIONS = EVE / "agent" / "lib" / "versions.ts"
GENERATED = "// Generated by eve/scripts/emit-skill-modules.py"
HEADER = GENERATED + " from skills/{name}/. Do not edit.\n"
MANUAL_HEADER = GENERATED + " from the manual-only skills' folders ({folders}). Do not edit.\n"
VERSIONS_HEADER = GENERATED + " from eve/package.json and the product's package.json. Do not edit.\n"
FRONTMATTER = re.compile(r"\A---\n(.*?)\n---\n", re.S)
IGNORED = {".DS_Store"}
EXACT_VERSION = re.compile(r"\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?")


def literal(text: str) -> str:
    """A TypeScript string literal for any text; JSON's escapes are valid there."""
    return json.dumps(text, ensure_ascii=False)


def split_frontmatter(text: str, name: str) -> tuple[str, str]:
    match = FRONTMATTER.match(text)
    if not match:
        raise SystemExit(f"skills/{name}/SKILL.md has no frontmatter")
    return match.group(1), text[match.end():].lstrip("\n")


def description(frontmatter: str, name: str) -> str:
    line = next((entry for entry in frontmatter.split("\n") if entry.startswith("description:")), None)
    raw = line[len("description:"):].strip() if line is not None else ""
    if not raw:
        raise SystemExit(f"skills/{name}/SKILL.md has no description")
    return json.loads(raw) if raw.startswith('"') else raw


def manual_only(skill_md: Path) -> bool:
    match = FRONTMATTER.match(skill_md.read_text(encoding="utf-8"))
    if not match:
        return False
    return any(re.fullmatch(r"disable-model-invocation:\s*true\s*", line)
               for line in match.group(1).splitlines())


def siblings(folder: Path, root: Path) -> list[tuple[str, bytes]]:
    """Every file under the skill folder but SKILL.md, by path relative to it, in name order."""
    found = []
    for path in sorted(folder.iterdir(), key=lambda entry: entry.name):
        if path.name in IGNORED:
            continue
        if path.is_symlink() or not (path.is_dir() or path.is_file()):
            raise SystemExit(f"skills/{path.relative_to(SKILLS)} is neither a file nor a folder")
        if path.is_dir():
            found.extend(siblings(path, root))
            continue
        key = path.relative_to(root).as_posix()
        if key != "SKILL.md":
            found.append((key, path.read_bytes()))
    return found


def package(name: str, indent: str) -> tuple[str, bool]:
    """The package as a SkillDefinition object literal, and whether it holds a base64 file."""
    folder = SKILLS / name
    frontmatter, body = split_frontmatter((folder / "SKILL.md").read_text(encoding="utf-8"), name)
    inner = indent + "  "
    lines = ["{", f"{inner}description: {literal(description(frontmatter, name))},",
             f"{inner}content: {literal(body)},", f"{inner}files: {{"]
    binary = False
    for key, data in siblings(folder, folder):
        try:
            value = literal(data.decode("utf-8"))
        except UnicodeDecodeError:
            value = f"fromBase64({literal(base64.b64encode(data).decode('ascii'))})"
            binary = True
        lines.append(f"{inner}  {literal(key)}: {value},")
    lines += [f"{inner}}},", f"{indent}}}"]
    return "\n".join(lines), binary


def imports(binary: bool, rest: str, lib: str) -> str:
    helper = f'import {{ fromBase64 }} from "{lib}skill-package";\n' if binary else ""
    return rest + helper


def skill_module(name: str) -> str:
    body, binary = package(name, "")
    return (HEADER.format(name=name)
            + imports(binary, 'import { defineSkill, type SkillDefinition } from "eve/skills";\n', "../lib/")
            + f"\nexport const skillPackage: SkillDefinition = {body};\n"
            + "\nexport default defineSkill(skillPackage);\n")


def manual_packages_module(names: list[str]) -> str:
    entries, binary = [], False
    for name in names:
        body, has_binary = package(name, "  ")
        entries.append(f"  {literal(name)}: {body},")
        binary = binary or has_binary
    folders = ", ".join(f"skills/{name}/" for name in names) or "none"
    return (MANUAL_HEADER.format(folders=folders)
            + imports(binary, 'import type { SkillDefinition } from "eve/skills";\n', "./")
            + "\n// The packages agent/skills/manual-only.ts serves once the user names the skill.\n"
            + "export const manualOnlyPackages = {\n" + "\n".join(entries)
            + ("\n" if entries else "") + "} satisfies Record<string, SkillDefinition>;\n")


def versions_module() -> str:
    pinned = json.loads((EVE / "package.json").read_text(encoding="utf-8"))["dependencies"]["eve"]
    if not EXACT_VERSION.fullmatch(pinned):
        raise SystemExit(f"eve/package.json pins eve as {pinned!r}; the run record needs an exact version")
    product = json.loads((EVE.parent / "package.json").read_text(encoding="utf-8"))["version"]
    return (VERSIONS_HEADER + 'import type { Versions } from "./run-state";\n'
            + "\n// The versions a run record carries: Eve's exact pin and the product's version.\n"
            + f"export const VERSIONS: Versions = {{ eve: {literal(pinned)}, product: {literal(product)} }};\n")


def expected() -> dict[Path, str]:
    """Every generated file's path to its content."""
    files, manual = {}, []
    for skill_md in sorted(SKILLS.glob("*/SKILL.md")):
        name = skill_md.parent.name
        if manual_only(skill_md):
            manual.append(name)
        else:
            files[MODULES / f"{name}.ts"] = skill_module(name)
    files[MANUAL_PACKAGES] = manual_packages_module(manual)
    files[VERSIONS] = versions_module()
    return files


def is_generated(path: Path) -> bool:
    return path.read_text(encoding="utf-8").startswith(GENERATED)


def shown(path: Path) -> str:
    return path.relative_to(EVE).as_posix()


def main(argv: list[str]) -> int:
    check = "--check" in argv
    want = expected()
    present = {p.name: p for p in MODULES.iterdir()} if MODULES.is_dir() else {}
    problems = []

    for name, path in sorted(present.items()):
        if name == RESOLVER or path in want:
            continue
        if path.is_file() and name.endswith(".ts") and is_generated(path):
            stem = name[:-3]
            reason = ("its skill is manual-only" if (SKILLS / stem / "SKILL.md").is_file()
                      else f"skills/{stem}/ does not exist")
            problems.append(f"orphan module {name}: {reason}")
            if not check:
                path.unlink()
        else:
            problems.append(f"foreign file agent/skills/{name}: only emitted modules and {RESOLVER} belong here")

    for path, content in want.items():
        if not path.is_file():
            if path.parent == MODULES:
                problems.append(f"missing module {path.name} for skills/{path.stem}/")
            else:
                problems.append(f"missing {shown(path)}")
        elif path.read_text(encoding="utf-8") != content:
            problems.append(f"drifted {'module ' + path.name if path.parent == MODULES else shown(path)}")
        else:
            continue
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")

    foreign = [p for p in problems if p.startswith("foreign")]
    for problem in problems:
        print(problem)
    if check and problems:
        print(f"emit-skill-modules: {len(problems)} problem(s); run eve/scripts/emit-skill-modules.py")
        return 1
    if foreign:
        return 1
    modules = sum(1 for path in want if path.parent == MODULES)
    print(f"emit-skill-modules: {modules} modules, {shown(MANUAL_PACKAGES)} and {shown(VERSIONS)} in sync")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
